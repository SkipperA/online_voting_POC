/// The hand-off between the two applications on one device.
///
/// In the browser the handover is a file the voter carries, and that
/// demonstrates the boundary: the only thing one origin can put into
/// another is a file, and the voting application cannot make the wallet do
/// anything. The browser goes on showing exactly that.
///
/// The phone shows the other thing. A wallet integrated at the dataflow
/// level is what a deployment has, and what the European Digital Identity
/// Wallet does by invocation with a consent screen -- so a demonstration
/// that only ever showed the file would be teaching an audience that the
/// integrated flow is unavailable rather than that it is a trade. Clause
/// A8 names the trade, and it is a real one: here the voting application
/// *can* make the wallet put a signing question in front of the voter. It
/// still cannot make them answer it, and nothing it sends identifies
/// anybody.
///
/// **What crosses is exactly what the file carried**, carried whole rather
/// than taken apart into query items. There is therefore one reader --
/// `WalletFlow.load` -- for both, one place the three fields are checked
/// against a configuration the wallet fetched itself, and no second
/// mapping to drift out of step with the first.
///
/// What does not cross, in either direction: the voter's identifier, which
/// the voting application does not have; the ad-hoc key, which it keeps;
/// and the blinding factor, which never leaves it. §5.3 is unchanged, and
/// so is the reason the wallet transmits to the office itself instead of
/// handing anything back.
///
/// Both applications are built from this package, so the scheme and the
/// query names cannot disagree in code. What *can* disagree is the
/// registration in each application's `Info.plist`, which is generated by
/// Xcode and not committed: `ios/README.md` carries those two steps and
/// `test_the_two_applications_agree_on_the_hand_off` keeps the three in
/// step.
import Foundation

public enum HandOff {
    /// Registered by the wallet application; opened by the voting one.
    public static let walletScheme = "ovpoc-wallet"
    /// Registered by the voting application; opened by the wallet.
    public static let voterScheme = "ovpoc-voter"

    static let requestHost = "request"
    static let collectedHost = "collected"
    static let payloadQuery = "r"
    static let outcomeQuery = "outcome"

    /// `ovpoc-wallet://request?r=…`, carrying the request file's own bytes.
    ///
    /// The bytes are passed through rather than unpacked, so that what the
    /// wallet reads is what the file would have contained. A hand-off that
    /// rebuilt the three fields would be a second renderer of the same
    /// object, and this project has learned twice what two renderers of
    /// one object cost.
    public static func toWallet(request bytes: Data) -> URL? {
        var url = URLComponents()
        url.scheme = walletScheme
        url.host = requestHost
        url.queryItems = [URLQueryItem(name: payloadQuery, value: bytes.b64url)]
        return url.url
    }

    /// The request bytes out of a hand-off, or `nil` if it is not one.
    ///
    /// `nil` rather than a throw: anything at all can open a URL scheme,
    /// so a malformed one is an ordinary event and not an alarm. What the
    /// bytes then say is checked by the same reader the file goes through,
    /// against a configuration the wallet fetches itself.
    public static func request(from url: URL) -> Data? {
        guard url.scheme == walletScheme, url.host == requestHost,
              let items = URLComponents(url: url, resolvingAgainstBaseURL: false)?
                  .queryItems,
              let payload = items.first(where: { $0.name == payloadQuery })?.value
        else { return nil }
        return Base64URL.decode(payload)
    }

    /// `ovpoc-voter://collected?outcome=…`, to put the voter back.
    ///
    /// The outcome and nothing else. The office's answer is already public
    /// to the voting application -- it collects `s_c` by presenting `c` --
    /// so naming it here discloses nothing new, and the alternative is a
    /// voter looking at a wallet wondering whether to switch back.
    public static func backToVoter(outcome: String) -> URL? {
        var url = URLComponents()
        url.scheme = voterScheme
        url.host = collectedHost
        url.queryItems = [URLQueryItem(name: outcomeQuery, value: outcome)]
        return url.url
    }

    /// What this build told the system it answers to.
    ///
    /// Read from the *running bundle*, and that is the whole point. The
    /// `Info.plist` in this repository is reached only if the target's
    /// `INFOPLIST_FILE` names it, and no test anywhere can see a build
    /// setting: `test_each_application_registers_the_scheme_the_other
    /// _opens_it_with` establishes that the committed file is right, and
    /// says nothing about whether the build read it.
    ///
    /// Unset, the build registers nothing, and the symptom is identical
    /// to a scheme spelled wrong -- the hand-off does nothing, nowhere,
    /// with no error on either side. An hour went into that once. A line
    /// on the screen saying what this binary actually answers to is the
    /// cheapest instrument that would have ended it, and it is the same
    /// argument `service/build.py` makes for printing the revision: a
    /// deployment that cannot say which code it is gets checked by
    /// proxies invented on the spot.
    public static func schemesRegistered(by bundle: Bundle = .main) -> [String] {
        schemes(in: bundle.object(forInfoDictionaryKey: "CFBundleURLTypes"))
    }

    /// The scheme list out of a `CFBundleURLTypes` value.
    ///
    /// Separated from the bundle so it can be tested: a `Bundle` with an
    /// arbitrary info dictionary is not something a test can build, and
    /// the part that goes wrong is the shape -- absent, not an array,
    /// an entry with no schemes.
    public static func schemes(in urlTypes: Any?) -> [String] {
        guard let entries = urlTypes as? [[String: Any]] else { return [] }
        return entries.flatMap { $0["CFBundleURLSchemes"] as? [String] ?? [] }
    }

    /// The outcome the wallet reported, or `nil` if this is not that.
    public static func outcome(from url: URL) -> String? {
        guard url.scheme == voterScheme, url.host == collectedHost,
              let items = URLComponents(url: url, resolvingAgainstBaseURL: false)?
                  .queryItems
        else { return nil }
        return items.first(where: { $0.name == outcomeQuery })?.value
    }
}
